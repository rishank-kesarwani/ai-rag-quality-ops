import { Injectable, Logger } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import axios, { AxiosInstance } from 'axios';

export interface NotificationAlertResult {
  sent: boolean;
  notificationId?: string;
  reason?: string;
}

@Injectable()
export class NotificationClient {
  private readonly logger = new Logger(NotificationClient.name);
  private readonly client: AxiosInstance;
  private readonly baseUrl: string;
  private readonly apiKey: string;
  private readonly recipientEmail: string;
  private readonly timeoutMs: number;

  constructor(private readonly configService: ConfigService) {
    this.baseUrl = this.configService
      .get<string>('notificationService.url', '')
      .replace(/\/$/, '');
    this.apiKey = this.configService.get<string>(
      'notificationService.apiKey',
      '',
    );
    this.recipientEmail = this.configService.get<string>(
      'notificationService.recipientEmail',
      'ops-alerts@example.com',
    );
    this.timeoutMs = this.configService.get<number>(
      'notificationService.timeoutMs',
      5000,
    );

    this.client = axios.create({
      baseURL: this.baseUrl || 'http://localhost:3001',
      timeout: this.timeoutMs,
      headers: {
        'Content-Type': 'application/json',
        ...(this.apiKey ? { 'x-api-key': this.apiKey } : {}),
      },
    });
  }

  isConfigured(): boolean {
    return !!this.baseUrl;
  }

  async checkHealth(): Promise<{
    status: string;
    latencyMs: number;
    error?: string;
  }> {
    if (!this.baseUrl) {
      return { status: 'UNCONFIGURED', latencyMs: 0 };
    }
    const start = Date.now();
    try {
      const res = await this.client.get('/health', { timeout: 3000 });
      return {
        status: res.status === 200 ? 'UP' : 'DEGRADED',
        latencyMs: Date.now() - start,
      };
    } catch (err: any) {
      return {
        status: 'DOWN',
        latencyMs: Date.now() - start,
        error: err.message,
      };
    }
  }

  /**
   * Dispatches alert notification via shared Notification Service POST /v1/notifications.
   * If service is offline or unconfigured, safely records structured log without crashing.
   */
  async sendAlert(
    subject: string,
    message: string,
    priority: 'CRITICAL' | 'BULK' = 'BULK',
    metadata?: Record<string, any>,
  ): Promise<NotificationAlertResult> {
    if (!this.baseUrl) {
      this.logger.log(
        `[Local Demo Mode] Notification alert simulated: "${subject}". Reason: Shared notification service unconfigured.`,
      );
      return {
        sent: true,
        notificationId: `sim-notif-${Date.now()}`,
        reason: 'Simulated locally (service unconfigured)',
      };
    }

    try {
      this.logger.log(
        `Dispatching notification alert to ${this.baseUrl}/v1/notifications`,
      );

      const payload = {
        priority,
        channels: ['EMAIL'],
        recipient: {
          userId: 'rag-quality-ops-admin',
          email: this.recipientEmail,
        },
        email: {
          subject: `[AI RAG Quality Ops] ${subject}`,
          text: message,
          html: `<div style="font-family: sans-serif; padding: 16px;">
            <h2>AI RAG Quality & Knowledge Ops Alert</h2>
            <p style="font-size: 16px;"><strong>${subject}</strong></p>
            <p>${message}</p>
            <hr/>
            <small style="color: #666;">Generated by AI RAG Quality Ops Platform</small>
          </div>`,
        },
        metadata: {
          service: 'ai-rag-quality-ops',
          timestamp: new Date().toISOString(),
          ...metadata,
        },
      };

      const res = await this.client.post('/v1/notifications', payload);
      const data = res.data?.data || res.data;

      return {
        sent: true,
        notificationId: data?.notificationId || `notif-${Date.now()}`,
      };
    } catch (err: any) {
      this.logger.warn(
        `Notification dispatch failed (${err.message}). Continuing execution.`,
      );
      return {
        sent: false,
        reason: err.message,
      };
    }
  }
}
